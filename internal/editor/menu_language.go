package editor

type menuLanguage string

const (
	menuChinese menuLanguage = "zh-CN"
	menuEnglish menuLanguage = "en"
)

var menuLanguages = [...]menuLanguage{menuChinese, menuEnglish}

func (language menuLanguage) name() string {
	if language == menuEnglish {
		return "English"
	}
	return "简体中文"
}

func (m *editorApp) menuText(label string) string {
	return m.menuLanguage.text(label)
}

func (language menuLanguage) text(label string) string {
	if language == menuEnglish {
		if translated, ok := englishMenuLabels[label]; ok {
			return translated
		}
		if translated, ok := englishInterfaceLabels()[label]; ok {
			return translated
		}
	}
	return label
}

